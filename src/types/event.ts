/**
 * EventAura Domain Types & Interfaces
 * Master data schema for celebration and event planning intelligence.
 */

/** Supported celebratory event archetypes */
export type EventType = 'wedding' | 'birthday' | 'community' | 'anniversary' | 'corporate';

/** Styling and aesthetic ambiance presets */
export type EventVibe = 'luxury' | 'rustic' | 'minimalist' | 'traditional' | 'modern-chic' | 'festive';

/** Supported international currency denominations */
export type Currency = 'INR' | 'USD' | 'EUR' | 'GBP';

/**
 * Relative priority weights for core budget partition categories.
 * Values range from 1 (minimal) to 5 (highest importance).
 */
export interface PriorityWeights {
  /** Venue rental & infrastructure priority */
  venue: number;
  /** Food, beverage & dining experience priority */
  catering: number;
  /** Photography, cinematography & memories priority */
  photography: number;
  /** Floral, stage, lighting & design priority */
  decor: number;
  /** Live music, DJ, performers & hosting priority */
  entertainment: number;
}

/**
 * Individual allocated budget category slice.
 */
export interface BudgetCategory {
  /** Unique category identifier */
  id: string;
  /** Category display title (e.g. Venue & Spaces) */
  name: string;
  /** Percentage of effective budget (0-100) */
  percentage: number;
  /** Absolute calculated financial amount allocated */
  allocatedAmount: number;
  /** Amount committed or spent to date */
  spentAmount: number;
  /** Thematic hex color code for chart visualization */
  color: string;
  /** Lucide icon identifier */
  icon: string;
  /** Contextual guidance notes explaining allocation */
  notes: string;
  /** AI suggested cost-saving trade-off advice */
  tradeoffAdvice?: string;
  /** Whether this category was user-customized */
  isCustom?: boolean;
}

/**
 * Complete financial partition plan.
 */
export interface BudgetPlan {
  /** Total gross event budget cap */
  totalBudget: number;
  /** Currency denomination */
  currency: Currency;
  /** Reserved emergency percentage buffer (e.g., 6%) */
  contingencyPercent: number;
  /** Exact emergency funds buffered */
  contingencyAmount: number;
  /** Sum of all category allocations */
  allocatedTotal: number;
  /** Unallocated or leftover buffer */
  remainingAmount: number;
  /** Partitioned category breakdown */
  categories: BudgetCategory[];
}

/** Task completion states */
export type TaskStatus = 'todo' | 'in_progress' | 'completed';

/** Relative task urgency */
export type TaskPriority = 'high' | 'medium' | 'low';

/** Chronological planning milestone phases */
export type MilestonePhase = 'early_prep' | 'vendor_lock' | 'details_invites' | 'final_countdown' | 'day_of';

/**
 * Structured planning task with dependency graph links.
 */
export interface TimelineTask {
  /** Unique task identifier */
  id: string;
  /** Task actionable title */
  title: string;
  /** Associated budget category */
  category: string;
  /** Milestone phase grouping */
  milestonePhase: MilestonePhase;
  /** Human-readable phase label */
  phaseLabel: string;
  /** Relative offset: number of days before target event date */
  daysBeforeEvent: number;
  /** Current progress status */
  status: TaskStatus;
  /** Urgency level (high, medium, low) */
  priority: TaskPriority;
  /** IDs of predecessor tasks that must complete first */
  dependencies?: string[];
  /** Human-readable titles of predecessor tasks */
  dependencyNames?: string[];
  /** Lead organizer or vendor responsible */
  assignedTo?: string;
  /** Contextual tip generated by GenAI */
  aiTip?: string;
}

/**
 * Micro-schedule item for event day execution.
 */
export interface RunOfShowItem {
  /** Unique item identifier */
  id: string;
  /** Clock time (e.g., '09:00 AM') */
  time: string;
  /** Scheduled activity description */
  activity: string;
  /** Lead coordinator on deck */
  leadPerson: string;
  /** Specific hall, lawn, or room */
  location: string;
  /** Operational notes or equipment cues */
  notes: string;
  /** Day-of checklist execution state */
  completed: boolean;
}

/**
 * Vendor comparison quote candidate.
 */
export interface VendorQuote {
  /** Unique quote identifier */
  id: string;
  /** Vendor commercial or business name */
  vendorName: string;
  /** Service category (Venue, Catering, Photography, etc.) */
  category: string;
  /** Total quoted contract price */
  quotedPrice: number;
  /** Optional per-plate or per-guest rate */
  perGuestRate?: number;
  /** Deliverables included in quote */
  inclusions: string[];
  /** Items excluded requiring surcharge */
  exclusions: string[];
  /** Contractual cancellation policy terms */
  cancellationPolicy: string;
  /** Quality reputation rating (1 to 5) */
  rating: number;
  /** Procurement evaluation status */
  status: 'evaluating' | 'shortlisted' | 'booked' | 'declined';
  /** Positive evaluation highlights */
  pros: string[];
  /** Identified risks or trade-offs */
  cons: string[];
  /** Alert regarding hidden overtime or service fees */
  hiddenChargesWarning?: string;
}

/**
 * Category-specific vetting probe for vendor negotiations.
 */
export interface VendorVettingQuestion {
  /** Unique probe identifier */
  id: string;
  /** Target vendor category */
  category: string;
  /** Specific question to ask the vendor */
  question: string;
  /** Strategic justification for the question */
  whyItMatters: string;
  /** Whether an unfavorable answer should disqualify the vendor */
  dealbreakerAlert: boolean;
}

/**
 * Personalized thematic hook or cultural ideation element.
 */
export interface PersonalizedIdea {
  /** Unique idea identifier */
  id: string;
  /** Creative title */
  title: string;
  /** Concept narrative */
  conceptDescription: string;
  /** Categorization tag */
  tag: 'Theme & Palette' | 'Culinary Experience' | 'Guest Engagement' | 'Atmosphere & Decor' | 'Entertainment & Memories';
  /** Expected budget impact */
  estimatedCostImpact: 'low' | 'medium' | 'high';
  /** Physical, dietary, or generational accessibility note */
  accessibilityConsideration?: string;
  /** Recommended vendor types to execute */
  suggestedVendors?: string[];
}

/**
 * Primary user intake specifications.
 */
export interface EventDetails {
  /** Unique plan identifier */
  id: string;
  /** Event title (e.g. Maya & Arjun Wedding) */
  title: string;
  /** Event archetype */
  type: EventType;
  /** Ambiance vibe */
  vibe: EventVibe;
  /** Target date in ISO YYYY-MM-DD format */
  targetDate: string;
  /** Expected attendee count */
  guestCount: number;
  /** Currency code */
  currency: Currency;
  /** Total financial ceiling */
  totalBudget: number;
  /** Geographic city or venue description */
  location: string;
  /** Accessibility requirements (wheelchair, quiet zones) */
  specialNeeds: string;
  /** Dietary preferences (Jain, Vegan, Halal, etc.) */
  dietaryPreferences: string[];
  /** Category priority weights (1-5) */
  priorities: PriorityWeights;
}

/**
 * Parameter shift for What-If scenario simulation.
 */
export interface ScenarioShift {
  /** Change in guest count (+/- guests) */
  guestCountDelta: number;
  /** Percentage change in budget (+/- %) */
  budgetPercentDelta: number;
  /** Change in schedule offset (+/- days) */
  daysOffsetDelta: number;
  /** Scenario scenario rationale (e.g. Budget Crunch) */
  description: string;
  /** Timestamp when shift was executed */
  appliedAt?: string;
}

/**
 * AI-formulated financial compromise option.
 */
export interface TradeOffOption {
  /** Unique trade-off identifier */
  id: string;
  /** Option name (e.g. Buffet Dining vs Plated Service) */
  title: string;
  /** Explanation of compromise */
  description: string;
  /** Expected net savings */
  budgetDelta: number;
  /** Advantages of taking this trade-off */
  pros: string[];
  /** Potential compromises to be aware of */
  cons: string[];
  /** Adjustments to category budget percentages */
  affectedCategories: { categoryId: string; newPercentage: number; deltaAmount: number }[];
}

/**
 * Unified Event Dossier aggregating all architectural modules.
 */
export interface EventPlan {
  /** High-level event metadata */
  details: EventDetails;
  /** Partitioned financial plan */
  budget: BudgetPlan;
  /** Sequential milestone tasks */
  tasks: TimelineTask[];
  /** Minute-by-minute day-of schedule */
  runOfShow: RunOfShowItem[];
  /** Comparative vendor quotes */
  vendorQuotes: VendorQuote[];
  /** Category negotiation probes */
  vettingQuestions: VendorVettingQuestion[];
  /** Personalized creative ideas */
  ideas: PersonalizedIdea[];
  /** Intelligent trade-off options */
  tradeOffOptions?: TradeOffOption[];
  /** Historical record of applied What-If shifts */
  scenarioHistory: ScenarioShift[];
  /** ISO timestamp of latest modification */
  lastUpdated: string;
}
